export type IconName = keyof typeof FM_ICONS;

/** `chevrons-up-down` → `fmChevronsUpDown`: ng-icons looks icons up by camelCase name. */
export function registryName(name: string): string {
    return 'fm' + name.replace(/(^|-)([a-z0-9])/g, (_m, _sep: string, c: string) => c.toUpperCase());
}

/** The registry as ng-icons wants it (camelCase keys); the kit addresses icons by kebab name. */
export const FM_ICON_REGISTRY: Record<string, string> = Object.fromEntries(Object.entries(FM_ICONS).map(([key, svg]) => [registryName(key), svg]));
